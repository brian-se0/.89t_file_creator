function printUsage() {
  print("Usage:");
  print("  jjs -cp <wordrider.jar> -scripting write_89t.js --input <input.txt> --output <output.89t> [options]");
  print("");
  print("Required:");
  print("  --input <path>       UTF-8 input text file");
  print("  --output <path>      Output .89t path");
  print("");
  print("Optional:");
  print("  --var-name <name>    TI variable name; sanitized and truncated to 8 chars");
  print("  --folder-name <name> TI folder name (default: main)");
  print("  --comment <text>     TI comment field (default: generated by WordRider)");
  print("  --store-type <type>  ram | ram-locked | archive (default: ram)");
  print("  --no-symbol-map      Skip Unicode-to-WordRider symbol replacement");
  print("  --help               Show this message");
}

function fail(message) {
  print("ERROR: " + message);
  java.lang.System.exit(1);
}

function countOccurrences(text, needle) {
  if (needle.length === 0) {
    return 0;
  }

  var count = 0;
  var index = text.indexOf(needle);
  while (index !== -1) {
    count += 1;
    index = text.indexOf(needle, index + needle.length);
  }
  return count;
}

function sanitizeVarName(name) {
  var cleaned = String(name).replace(/[^A-Za-z0-9_]/g, "");
  if (!cleaned) {
    cleaned = "textfile";
  }
  if (/^[0-9]/.test(cleaned)) {
    cleaned = "v" + cleaned;
  }
  return cleaned.substring(0, 8);
}

function deriveVarName(outputPathText) {
  var fileName = String(Paths.get(outputPathText).getFileName().toString());
  if (/\.89t$/i.test(fileName)) {
    fileName = fileName.substring(0, fileName.length - 4);
  }
  return sanitizeVarName(fileName);
}

function parseArguments(rawArgs) {
  var parsed = {
    folderName: "main",
    comment: "generated by WordRider",
    storeType: "ram",
    useSymbolMap: true
  };

  for (var i = 0; i < rawArgs.length; i += 1) {
    var arg = String(rawArgs[i]);

    if (arg === "--help" || arg === "-h") {
      parsed.help = true;
      continue;
    }

    if (arg === "--no-symbol-map") {
      parsed.useSymbolMap = false;
      continue;
    }

    if (arg.indexOf("--") !== 0) {
      fail("Unexpected argument: " + arg);
    }

    if (i + 1 >= rawArgs.length) {
      fail("Missing value for " + arg);
    }

    var value = String(rawArgs[i + 1]);
    i += 1;

    if (arg === "--input") {
      parsed.input = value;
    } else if (arg === "--output") {
      parsed.output = value;
    } else if (arg === "--var-name") {
      parsed.varName = value;
    } else if (arg === "--folder-name") {
      parsed.folderName = value;
    } else if (arg === "--comment") {
      parsed.comment = value;
    } else if (arg === "--store-type") {
      parsed.storeType = value.toLowerCase();
    } else {
      fail("Unknown option: " + arg);
    }
  }

  return parsed;
}

function applySymbolReplacements(text) {
  var totalReplacements = 0;
  var touchedLabels = [];
  var currentText = text;

  for (var i = 0; i < SYMBOL_REPLACEMENTS.length; i += 1) {
    var replacement = SYMBOL_REPLACEMENTS[i];
    var occurrences = countOccurrences(currentText, replacement.from);
    if (occurrences > 0) {
      currentText = currentText.split(replacement.from).join(replacement.to);
      totalReplacements += occurrences;
      touchedLabels.push(replacement.label + "=" + occurrences);
    }
  }

  return {
    text: currentText,
    totalReplacements: totalReplacements,
    touchedLabels: touchedLabels
  };
}

var args = parseArguments($ARG);
if (args.help) {
  printUsage();
  java.lang.System.exit(0);
}

if (!args.input) {
  fail("Missing required --input");
}
if (!args.output) {
  fail("Missing required --output");
}
if (!STORE_TYPES.hasOwnProperty(args.storeType)) {
  fail("Invalid --store-type. Expected ram, ram-locked, or archive.");
}

var inputPath = Paths.get(args.input).toAbsolutePath().normalize();
var outputPath = Paths.get(args.output).toAbsolutePath().normalize();

if (!Files.exists(inputPath)) {
  fail("Input file not found: " + inputPath);
}

if (outputPath.getParent() !== null) {
  Files.createDirectories(outputPath.getParent());
}

var text = new java.lang.String(Files.readAllBytes(inputPath), StandardCharsets.UTF_8);
var replacementResult = {
  text: text,
  totalReplacements: 0,
  touchedLabels: []
};

if (args.useSymbolMap) {
  replacementResult = applySymbolReplacements(text);
}

var varName = sanitizeVarName(args.varName ? args.varName : deriveVarName(String(outputPath)));
var folderName = String(args.folderName || "main");
var comment = String(args.comment || "generated by WordRider");
var storeTypeValue = STORE_TYPES[args.storeType];

var writer = new TITextFileWriter();
var info = new TIFileInfo();
info.setFolderName(folderName);
info.setComment(comment);
info.setVarName(varName);
info.setStoreType(storeTypeValue, false);
writer.setFileInfo(info);
writer.setTextContent(replacementResult.text);

var saved = writer.saveToFile(new File(String(outputPath)));
if (!saved) {
  fail("TITextFileWriter returned false while saving " + outputPath);
}

print("saved=true");
print("input=" + inputPath);
print("output=" + outputPath);
print("varName=" + varName);
print("folderName=" + folderName);
print("storeType=" + args.storeType);
print("symbolMapApplied=" + args.useSymbolMap);
print("symbolReplacements=" + replacementResult.totalReplacements);
if (replacementResult.touchedLabels.length > 0) {
  print("replacementBreakdown=" + replacementResult.touchedLabels.join(","));
}
print("inputChars=" + text.length());
print("outputChars=" + replacementResult.text.length());
